// Generates supabase/migrations/..._seed.sql from the TypeScript content files,
// so the app's bundled fallback content and the database never drift apart.
// Run: npm run gen:seed
import { writeFileSync } from 'node:fs'
import { ARTICLES } from '../src/content/articles.ts'
import { MYTHS } from '../src/content/myths.ts'
import { QUIZ } from '../src/content/quiz.ts'

const q = (s: string | null) => (s == null ? 'null' : `'${s.replace(/'/g, "''")}'`)
const arr = (xs: string[]) => `array[${xs.map(q).join(', ')}]::text[]`

let sql = `-- Generated by scripts/gen-seed.ts — do not edit by hand.\n\n`
sql += `truncate public.articles, public.myths, public.quiz_questions restart identity;\n\n`
for (const a of ARTICLES)
  sql += `insert into public.articles (slug, position, letter, nav_label, title, summary, body) values (${q(a.slug)}, ${a.position}, ${q(a.letter)}, ${q(a.nav_label)}, ${q(a.title)}, ${q(a.summary)}, ${q(JSON.stringify(a.body))}::jsonb);\n`
sql += '\n'
for (const m of MYTHS)
  sql += `insert into public.myths (myth, fact, category, source) values (${q(m.myth)}, ${q(m.fact)}, ${q(m.category)}, ${q(m.source)});\n`
sql += '\n'
for (const x of QUIZ)
  sql += `insert into public.quiz_questions (position, question, options, correct_index, explanation) values (${x.position}, ${q(x.question)}, ${arr(x.options)}, ${x.correct_index}, ${q(x.explanation)});\n`

writeFileSync('supabase/migrations/20261119000002_seed.sql', sql)
console.log(`Seed written: ${ARTICLES.length} articles, ${MYTHS.length} myths, ${QUIZ.length} questions`)
